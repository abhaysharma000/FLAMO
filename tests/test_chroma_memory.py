# 15. Opt-in SQLite to ChromaDB Migration Script
# ==============================================================================

def test_sqlite_to_chroma_migration(tmp_path: Path, fake_embeddings: Embeddings):
    sqlite_db = tmp_path / "source.db"
    chroma_dir = str(tmp_path / "chroma_migrated")

    # Seed SQLite
    sql_store = SqliteMemoryStore(db_path=str(sqlite_db))
    sql_store.store(
        MemoryItem(
            id="mig-1",
            category=MemoryCategory.REUSABLE_KNOWLEDGE,
            content="Knowledge to migrate",
            metadata={"orig": "sql"},
            task_id="t-1",
        )
    )
    sql_store.store(
        MemoryItem(
            id="mig-2",
            category=MemoryCategory.USER_PREFERENCES,
            content="Preference to migrate",
            metadata={"orig": "pref"},
            task_id="t-2",
        )
    )

    # 1. Test Dry Run: records read = 2, migrated = 2 (in dry run), Chroma untouched
    dry_stats = migrate_sqlite_to_chroma(
        sqlite_db_path=str(sqlite_db),
        chroma_dir=chroma_dir,
        dry_run=True,
        embeddings=fake_embeddings,
    )
    assert dry_stats["read"] == 2
    assert dry_stats["migrated"] == 2
    assert dry_stats["skipped"] == 0

    # 2. Test Real Migration
    real_stats = migrate_sqlite_to_chroma(
        sqlite_db_path=str(sqlite_db),
        chroma_dir=chroma_dir,
        dry_run=False,
        embeddings=fake_embeddings,
    )
    assert real_stats["read"] == 2
    assert real_stats["migrated"] == 2
    assert real_stats["skipped"] == 0
    assert real_stats["failed"] == 0

    # Verify records present in Chroma
    chroma = ChromaMemoryStore(persist_directory=chroma_dir, embeddings=fake_embeddings)
    m1 = chroma.retrieve("Knowledge to migrate", limit=1)
    assert len(m1) == 1
    assert m1[0].id == "mig-1"
    assert m1[0].metadata.get("orig") == "sql"

    # 3. Test Rerun (Idempotency): records should be skipped, not duplicated
    rerun_stats = migrate_sqlite_to_chroma(
        sqlite_db_path=str(sqlite_db),
        chroma_dir=chroma_dir,
        dry_run=False,
        embeddings=fake_embeddings,
    )
    assert rerun_stats["read"] == 2
    assert rerun_stats["migrated"] == 0
    assert rerun_stats["skipped"] == 2
    assert rerun_stats["failed"] == 0

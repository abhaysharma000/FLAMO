    # Destroy instance 1
    del store1

    # Recreate store in instance 2 pointing to the same persistent directory
    store2 = ChromaMemoryStore(
        persist_directory=chroma_tmp_dir,
        collection_name=coll_name,
        embeddings=fake_embeddings,
    )

    retrieved = store2.retrieve("enterprise architecture guideline", limit=2)
    assert len(retrieved) == 1
    assert retrieved[0].id == "persist-fact-1"
    assert retrieved[0].content == "Critical durable enterprise architecture guideline."
    assert retrieved[0].task_id == "task-bootstrap-101"
    assert retrieved[0].metadata.get("source") == "whitepaper"



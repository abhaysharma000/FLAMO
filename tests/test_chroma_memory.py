# 1. Store and Retrieve by Semantic Similarity
# ==============================================================================

def test_store_and_retrieve_semantic_similarity(chroma_store: ChromaMemoryStore):
    store = chroma_store

    item1 = MemoryItem(
        id="mem-langgraph",
        category=MemoryCategory.REUSABLE_KNOWLEDGE,
        content="LangGraph utilizes StateGraph to construct stateful cyclic agent workflows.",
        metadata={"ecosystem": "langchain"},
    )
    item2 = MemoryItem(
        id="mem-crewai",
        category=MemoryCategory.REUSABLE_KNOWLEDGE,
        content="CrewAI organizes collaborative autonomous role-playing agents in crews.",
        metadata={"ecosystem": "crewai"},
    )
    item3 = MemoryItem(
        id="mem-astronomy",
        category=MemoryCategory.REUSABLE_KNOWLEDGE,
        content="Gravitational waves are ripples in spacetime generated by colliding black holes.",
        metadata={"subject": "physics"},
    )

    store.store(item1)
    store.store(item2)
    store.store(item3)

    # Search for agent workflows (should match item1 top)
    results = store.retrieve("StateGraph agent workflow cycle", limit=2)
    assert len(results) >= 1
    assert results[0].id == "mem-langgraph"
    assert results[0].relevance_score is not None
    assert results[0].relevance_score > 0.1

    # Search for astronomy
    astro_results = store.retrieve("spacetime ripples colliding black holes", limit=1)
    assert len(astro_results) == 1
    assert astro_results[0].id == "mem-astronomy"



# 14. FastAPI Memory Endpoints Integration
# ==============================================================================

def test_fastapi_memory_routes_integration():
    client = TestClient(app)

    # 1. Store memory via POST /api/memory
    payload = {
        "category": "reusable_knowledge",
        "content": "FastAPI memory endpoint verification item for Phase 5.",
        "metadata": {"test_source": "fastapi_test"},
        "task_id": "task-api-test-1",
    }
    response = client.post("/api/memory", json=payload)
    assert response.status_code == 201
    data = response.json()
    assert "id" in data
    assert data["status"] == "stored"
    created_id = data["id"]

    # 2. Search memory via GET /api/memory/search
    search_resp = client.get(
        "/api/memory/search",
        params={"query": "FastAPI memory endpoint verification", "limit": 2},
    )
    assert search_resp.status_code == 200
    search_data = search_resp.json()
    assert len(search_data) >= 1
    assert any(m["id"] == created_id for m in search_data)

    # 3. Delete memory via DELETE /api/memory/{id}
    del_resp = client.delete(f"/api/memory/{created_id}")
    assert del_resp.status_code == 200
    assert del_resp.json()["deleted"] is True



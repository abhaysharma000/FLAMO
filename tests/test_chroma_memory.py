# 3. Update Existing ID Without Producing Duplicate Logical Records
# ==============================================================================

def test_update_existing_id_without_duplicates(chroma_store: ChromaMemoryStore):
    store = chroma_store

    item_v1 = MemoryItem(
        id="mem-upd-1",
        category=MemoryCategory.REUSABLE_KNOWLEDGE,
        content="Version 1: Preliminary benchmark analysis",
        metadata={"version": 1},
    )
    store.store(item_v1)

    # Verify 1 record present
    raw_v1 = store._vector_store.get(ids=["mem-upd-1"])
    assert len(raw_v1["ids"]) == 1
    assert raw_v1["documents"][0] == "Version 1: Preliminary benchmark analysis"

    # Update with Version 2 under the identical ID
    item_v2 = MemoryItem(
        id="mem-upd-1",
        category=MemoryCategory.REUSABLE_KNOWLEDGE,
        content="Version 2: Final authoritative benchmark analysis",
        metadata={"version": 2, "verified": True},
    )
    store.store(item_v2)

    # Verify no duplicate logical records in Chroma collection
    raw_v2 = store._vector_store.get(ids=["mem-upd-1"])
    assert len(raw_v2["ids"]) == 1
    assert raw_v2["documents"][0] == "Version 2: Final authoritative benchmark analysis"

    # Verify retrieve returns single updated document
    results = store.retrieve("benchmark analysis", limit=5)
    matching = [r for r in results if r.id == "mem-upd-1"]
    assert len(matching) == 1
    assert "Version 2" in matching[0].content
    assert matching[0].metadata.get("version") == 2



class SemanticFakeEmbeddings(Embeddings):
    """Deterministic, normalized offline embedding generator for isolated unit testing."""

    def __init__(self, dimensions: int = 128) -> None:
        self.dimensions = dimensions

    def _word_vec(self, word: str) -> np.ndarray:
        token = _stem(word)
        seed = sum(ord(c) * (i + 1) for i, c in enumerate(token)) % (2**31 - 1)
        rng = np.random.RandomState(seed)
        v = rng.randn(self.dimensions)
        norm = np.linalg.norm(v)
        return v / norm if norm > 0 else v

    def embed_query(self, text: str) -> list[float]:
        raw_words = re.findall(r"[a-z0-9]+", text.lower())
        words = [w for w in raw_words if len(w) > 1]
        if not words:
            return [0.0] * self.dimensions
        v = sum(self._word_vec(w) for w in words)
        norm = np.linalg.norm(v)
        return (v / norm if norm > 0 else v).tolist()

    def embed_documents(self, texts: list[str]) -> list[list[float]]:
        return [self.embed_query(t) for t in texts]



# 12. Handle Empty Queries, Missing Metadata, and Invalid Config Safely
# ==============================================================================

def test_empty_queries_and_invalid_backend(chroma_store: ChromaMemoryStore):
    store = chroma_store

    # Empty and whitespace queries safely return []
    assert store.retrieve("") == []
    assert store.retrieve("   ") == []

    # Invalid backend name in get_memory_store fails explicitly
    with pytest.raises(ValueError, match="Unsupported MEMORY_BACKEND 'redis'"):
        get_memory_store(backend="redis")

    # Missing API key with MEMORY_BACKEND=chroma fails explicitly
    orig_key = os.environ.get("GEMINI_API_KEY", "")
    orig_gkey = os.environ.get("GOOGLE_API_KEY", "")
    try:
        os.environ["GEMINI_API_KEY"] = ""
        os.environ["GOOGLE_API_KEY"] = ""
        settings.gemini_api_key = ""
        with pytest.raises(ValueError, match="CRITICAL CONFIGURATION ERROR"):
            get_memory_store(backend="chroma")
    finally:
        os.environ["GEMINI_API_KEY"] = orig_key
        os.environ["GOOGLE_API_KEY"] = orig_gkey
        settings.gemini_api_key = orig_key


